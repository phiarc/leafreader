import { readdir } from 'node:fs/promises';
import { join, relative } from 'node:path';

export function assetMimeType(path) {
  const extension = path.split('.').at(-1)?.toLowerCase();
  return ({ html:'text/html', js:'text/javascript', mjs:'text/javascript', css:'text/css', json:'application/json',
    wasm:'application/wasm', svg:'image/svg+xml', png:'image/png', jpg:'image/jpeg', jpeg:'image/jpeg',
    webp:'image/webp', woff:'font/woff', woff2:'font/woff2', ttf:'font/ttf', otf:'font/otf', txt:'text/plain' })[extension] || 'application/octet-stream';
}

export async function collectHarmonyAssets(root) {
  const entries = [];
  async function visit(directory) {
    for (const entry of await readdir(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) await visit(path);
      else if (entry.isFile()) {
        const resource = relative(root, path).split('\\').join('/');
        entries.push({ urlPath: `/reader/${resource}`, rawfile: `reader/${resource}`, mimeType: assetMimeType(resource) });
      }
    }
  }
  await visit(root);
  return entries.sort((a,b) => a.urlPath.localeCompare(b.urlPath));
}

export function renderHarmonyManifest(entries) {
  const rows = entries.map(entry => `  [${JSON.stringify(entry.urlPath)}, ${JSON.stringify(entry.rawfile)}]`).join(',\n');
  const mimeRows = entries.map(entry => `  [${JSON.stringify(entry.urlPath)}, ${JSON.stringify(entry.mimeType)}]`).join(',\n');
  return `// Generated by scripts/package-web.mjs; packaged files only.\nexport const LOCAL_ASSETS: Map<string, string> = new Map<string, string>([\n${rows}\n]);\nexport const LOCAL_MIME_TYPES: Map<string, string> = new Map<string, string>([\n${mimeRows}\n]);\n`;
}
